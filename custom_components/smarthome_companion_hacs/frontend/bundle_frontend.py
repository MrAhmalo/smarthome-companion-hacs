#!/usr/bin/env python3
"""
bundle_frontend.py: Zero-dependency Python bundler for SmartHome Companion OS Frontend.
Concatenates ES modules in topological order into a single production bundle:
  frontend/dist/companion-dashboard.bundle.js
"""
import os
import re

FRONTEND_DIR = os.path.dirname(os.path.abspath(__file__))
DIST_DIR = os.path.join(FRONTEND_DIR, "dist")
OUTPUT_FILE = os.path.join(DIST_DIR, "companion-dashboard.bundle.js")

# Topological dependency order
FILES_IN_ORDER = [
    "lib/styles.js",
    "lib/util.js",
    "components/color_picker.js",
    "components/custom_dropdown.js",
    "components/icon_picker.js",
    "components/entity_picker.js",
    "components/tile.js",
    "components/room.js",
    "components/room_detail.js",
    "components/warning_detail.js",
    "components/specials.js",
    "components/settings.js",
    "components/room_modals.js",
    "components/device_wizard.js",
    "companion-dashboard.js",
]

# Regex to strip local relative import statements
IMPORT_RE = re.compile(r"""^\s*import\s+(?:\{[^}]*\}|[\w]+|\*\s+as\s+[\w]+)\s+from\s+['"](?:\.\.?\/)[^'"]+['"];?\s*""", re.MULTILINE | re.DOTALL)
# Regex to strip "export " keyword before class, const, let, function, async
EXPORT_KEYWORD_RE = re.compile(r"""^\s*export\s+(?=(?:class|const|let|var|function|async\s+function)\b)""", re.MULTILINE)
# Regex to strip standalone export { ... };
EXPORT_BLOCK_RE = re.compile(r"""^\s*export\s*\{[^}]*\};?\s*""", re.MULTILINE | re.DOTALL)

def bundle():
    os.makedirs(DIST_DIR, exist_ok=True)
    bundle_parts = [
        "// SmartHome Companion OS - Single-Bundle Frontend",
        "// Auto-generated by bundle_frontend.py. Do not edit directly.",
        "(() => {",
    ]

    for rel_path in FILES_IN_ORDER:
        full_path = os.path.join(FRONTEND_DIR, rel_path)
        if not os.path.exists(full_path):
            print(f"ERROR: Missing file {full_path}")
            return False

        with open(full_path, "r", encoding="utf-8") as f:
            code = f.read()

        # Strip imports of other modules in our bundle
        code = IMPORT_RE.sub("", code)
        # Strip export keywords
        code = EXPORT_KEYWORD_RE.sub("", code)
        code = EXPORT_BLOCK_RE.sub("", code)

        bundle_parts.append(f"\n// ─── START: {rel_path} ───")
        bundle_parts.append(code.strip())
        bundle_parts.append(f"// ─── END: {rel_path} ───\n")

    bundle_parts.append("})();\n")

    bundle_content = "\n".join(bundle_parts)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as out:
        out.write(bundle_content)

    size = os.path.getsize(OUTPUT_FILE)
    print(f"SUCCESS: Bundled {len(FILES_IN_ORDER)} modules into {OUTPUT_FILE} ({size} bytes)")
    return True

if __name__ == "__main__":
    bundle()

